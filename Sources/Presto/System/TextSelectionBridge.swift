import AppKit
import ApplicationServices
import Carbon
import Foundation

public struct CapturedSelection: Sendable {
    public let text: String
    public let sourceAppPID: pid_t?
    public let sourceAppName: String?
    public let anchorPoint: CGPoint

    public init(text: String, sourceAppPID: pid_t?, sourceAppName: String?, anchorPoint: CGPoint) {
        self.text = text
        self.sourceAppPID = sourceAppPID
        self.sourceAppName = sourceAppName
        self.anchorPoint = anchorPoint
    }
}

public enum SelectionBridgeError: LocalizedError, Sendable {
    case accessibilityPermissionRequired
    case noSelection
    case targetAppUnavailable

    public var errorDescription: String? {
        switch self {
        case .accessibilityPermissionRequired:
            return "Enable Accessibility access for Presto in System Settings."
        case .noSelection:
            return "No highlighted text found."
        case .targetAppUnavailable:
            return "Could not return focus to the target app."
        }
    }
}

private struct PasteboardSnapshot {
    struct ItemData {
        let representations: [(NSPasteboard.PasteboardType, Data)]
    }

    let items: [ItemData]

    static func capture(from pasteboard: NSPasteboard) -> PasteboardSnapshot {
        let capturedItems: [ItemData] = (pasteboard.pasteboardItems ?? []).map { item in
            let reps = item.types.compactMap { type -> (NSPasteboard.PasteboardType, Data)? in
                guard let data = item.data(forType: type) else { return nil }
                return (type, data)
            }
            return ItemData(representations: reps)
        }
        return PasteboardSnapshot(items: capturedItems)
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let restored: [NSPasteboardItem] = items.compactMap { itemData in
            guard !itemData.representations.isEmpty else { return nil }
            let item = NSPasteboardItem()
            for (type, data) in itemData.representations {
                item.setData(data, forType: type)
            }
            return item
        }
        if !restored.isEmpty {
            pasteboard.writeObjects(restored)
        }
    }
}

@MainActor
public final class TextSelectionBridge {
    public static let shared = TextSelectionBridge()

    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private init() {}

    public func captureSelection() async throws -> CapturedSelection {
        guard AXIsProcessTrusted() else {
            throw SelectionBridgeError.accessibilityPermissionRequired
        }

        let frontApp = NSWorkspace.shared.frontmostApplication
        let ownPID = ProcessInfo.processInfo.processIdentifier
        let targetApp = (frontApp?.processIdentifier == ownPID) ? nil : frontApp

        let mouseLocation = NSEvent.mouseLocation
        let (axText, axAnchor) = readSelectionViaAccessibility()
        let anchorPoint = axAnchor ?? mouseLocation

        if let axText, !axText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return CapturedSelection(
                text: axText,
                sourceAppPID: targetApp?.processIdentifier,
                sourceAppName: targetApp?.localizedName,
                anchorPoint: anchorPoint
            )
        }

        let copiedText = try await copySelectionViaPasteboard()
        guard !copiedText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw SelectionBridgeError.noSelection
        }

        return CapturedSelection(
            text: copiedText,
            sourceAppPID: targetApp?.processIdentifier,
            sourceAppName: targetApp?.localizedName,
            anchorPoint: anchorPoint
        )
    }

    public func replaceSelection(_ selection: CapturedSelection, with translatedText: String) async throws {
        guard AXIsProcessTrusted() else {
            throw SelectionBridgeError.accessibilityPermissionRequired
        }

        if let pid = selection.sourceAppPID {
            guard let targetApp = NSRunningApplication(processIdentifier: pid), !targetApp.isTerminated else {
                throw SelectionBridgeError.targetAppUnavailable
            }

            if NSWorkspace.shared.frontmostApplication?.processIdentifier != pid {
                targetApp.activate()
                for _ in 0..<25 {
                    if NSWorkspace.shared.frontmostApplication?.processIdentifier == pid {
                        break
                    }
                    try? await Task.sleep(for: .milliseconds(15))
                }
                try? await Task.sleep(for: .milliseconds(45))
            }
        }

        let pasteboard = NSPasteboard.general
        let snapshot = PasteboardSnapshot.capture(from: pasteboard)

        pasteboard.clearContents()
        let transientItem = NSPasteboardItem()
        transientItem.setString(translatedText, forType: .string)
        transientItem.setData(Data(), forType: Self.transientType)
        transientItem.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.writeObjects([transientItem])

        postCommandShortcut(virtualKey: CGKeyCode(kVK_ANSI_V))

        try? await Task.sleep(for: .milliseconds(200))
        snapshot.restore(to: pasteboard)
    }

    private func readSelectionViaAccessibility() -> (String?, CGPoint?) {
        let systemWide = AXUIElementCreateSystemWide()
        var focusedRef: CFTypeRef?
        let focusStatus = AXUIElementCopyAttributeValue(
            systemWide,
            kAXFocusedUIElementAttribute as CFString,
            &focusedRef
        )
        guard focusStatus == .success, let focusedRef else {
            return (nil, nil)
        }
        // CoreFoundation opaque type cast verified by kAXFocusedUIElementAttribute contract
        let element = unsafeDowncast(focusedRef, to: AXUIElement.self)

        var selectedTextRef: CFTypeRef?
        let textStatus = AXUIElementCopyAttributeValue(
            element,
            kAXSelectedTextAttribute as CFString,
            &selectedTextRef
        )
        let text = (textStatus == .success) ? (selectedTextRef as? String) : nil

        let anchor = readSelectionAnchorPoint(from: element)
        return (text, anchor)
    }

    private func readSelectionAnchorPoint(from element: AXUIElement) -> CGPoint? {
        var rangeRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(
            element,
            kAXSelectedTextRangeAttribute as CFString,
            &rangeRef
        ) == .success, let rangeRef else {
            return nil
        }

        var boundsRef: CFTypeRef?
        guard AXUIElementCopyParameterizedAttributeValue(
            element,
            kAXBoundsForRangeParameterizedAttribute as CFString,
            rangeRef,
            &boundsRef
        ) == .success, let boundsRef else {
            return nil
        }

        let axValue = unsafeDowncast(boundsRef, to: AXValue.self)
        var quartzRect = CGRect.zero
        guard AXValueGetValue(axValue, .cgRect, &quartzRect),
              quartzRect.width >= 0,
              !quartzRect.isNull,
              !quartzRect.isInfinite,
              quartzRect != .zero else {
            return nil
        }

        // Convert Quartz global coordinates (origin top-left of primary display) to AppKit screen coordinates
        let primaryHeight = NSScreen.screens.first?.frame.height ?? 0
        let cocoaY = primaryHeight - (quartzRect.origin.y + quartzRect.height)
        return CGPoint(x: quartzRect.midX, y: cocoaY)
    }

    private func copySelectionViaPasteboard() async throws -> String {
        let pasteboard = NSPasteboard.general
        let snapshot = PasteboardSnapshot.capture(from: pasteboard)
        defer {
            snapshot.restore(to: pasteboard)
        }

        pasteboard.clearContents()
        let markerItem = NSPasteboardItem()
        markerItem.setData(Data(), forType: Self.transientType)
        markerItem.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.writeObjects([markerItem])
        let baselineCount = pasteboard.changeCount

        postCommandShortcut(virtualKey: CGKeyCode(kVK_ANSI_C))

        for _ in 0..<20 {
            try? await Task.sleep(for: .milliseconds(15))
            if pasteboard.changeCount != baselineCount {
                if let copied = pasteboard.string(forType: .string), !copied.isEmpty {
                    return copied
                }
                break
            }
        }

        throw SelectionBridgeError.noSelection
    }

    private func postCommandShortcut(virtualKey: CGKeyCode) {
        let source = CGEventSource(stateID: .privateState)
        guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: virtualKey, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: source, virtualKey: virtualKey, keyDown: false) else {
            return
        }
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand
        keyDown.post(tap: .cgAnnotatedSessionEventTap)
        keyUp.post(tap: .cgAnnotatedSessionEventTap)
    }
}
